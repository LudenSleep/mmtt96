"""Health chain differential pairs: run one pair, or summarise the chain.

  pairs.py <pair> [--plant]     run one pair; prints `pair <name>: agree|DISAGREE (<counts>)`, writes
                                .run/mmtt96-health/pairs/<name>; exit 0 iff agree
  pairs.py summary              prints every pair line + `health: pairs <a>/<n> agree`, writes
                                .run/mmtt96-health/report.txt; exit 0 iff a == n (a missing result is DISAGREE)

Pairs: boundaries srcform incremental census mirror coverage checkmaps (DK-9, plan 1.5 ## Rationale) signatures
(plan 1.6 T2: registry check vs a recomputed control row) names (T3: names-on vs --no-names listing + mirror).
--plant injects one defect into a scratch copy under .run/mmtt96-health/plant/ and must exit 1 (G25, C0008);
a planted run writes no pair result. Child tool output goes to .run/mmtt96-health/logs/<name>.log, never stdout
(G12: stdout and the report carry ids and counts only). Make is $MAKE or `make`. Stdlib only.
"""
import csv
import hashlib
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEALTH = os.path.join(ROOT, ".run", "mmtt96-health")
PAIRS_DIR = os.path.join(HEALTH, "pairs")
PLANT_DIR = os.path.join(HEALTH, "plant")
LOGS = os.path.join(HEALTH, "logs")
REPORT = os.path.join(HEALTH, "report.txt")
REGIONS = os.path.join(ROOT, "config", "regions.retail.tsv")
GHIDRA_REGIONS = os.path.join(ROOT, "config", "ghidra", "regions.tsv")
MANIFEST = os.path.join(ROOT, "config", "manifest.retail.jsonl")
CHECK_SHA = os.path.join(ROOT, "config", "check.retail.sha")
COVERAGE_TSV = os.path.join(ROOT, "config", "oracle", "coverage.tsv")
ROM_MAPS = os.path.join(ROOT, "config", "maps", "rom.tsv")
ROM = os.path.join(ROOT, "disks", "Micro Machines Turbo Tournament 96 (Europe) (v1.1) (J-Cart).md")
BIN = os.path.join(ROOT, "build", "mmtt96.bin")
SRC_DIR = os.path.join(ROOT, "asm", "src")
SRCLIST = os.path.join(ROOT, "asm", ".srclist")
PY = sys.executable
MAKE = os.environ.get("MAKE") or "make"
PLANT_ID = "code_0002FA"


def run(name, cmd):
    """Run cmd from ROOT, output appended to the pair's log -> (exit code, captured stdout text)."""
    os.makedirs(LOGS, exist_ok=True)
    p = subprocess.run(cmd, cwd=ROOT, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    out = p.stdout.decode("utf-8", errors="replace")
    with open(os.path.join(LOGS, name + ".log"), "a", encoding="utf-8", newline="\n") as f:
        f.write("$ %s\n%s[exit %d]\n" % (" ".join(cmd), out, p.returncode))
    return p.returncode, out


def py(name, script, *args):
    return run(name, [PY, os.path.join(ROOT, *script.split("/"))] + list(args))


def sha1(path):
    with open(path, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()


def want_sha1():
    with open(CHECK_SHA, encoding="utf-8") as f:
        return f.read().split()[0].lower()


def read_tsv(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))


def scratch(name):
    d = os.path.join(PLANT_DIR, name)
    os.makedirs(d, exist_ok=True)
    return d


def flip(path):
    """Scratch copy of a leg's bin with its first byte flipped (pairs 2 and 3 plant)."""
    out = os.path.join(scratch("bin"), "flipped_" + os.path.basename(path))
    with open(path, "rb") as f:
        data = bytearray(f.read())
    data[0] ^= 0xFF
    with open(out, "wb") as f:
        f.write(data)
    return out


def keep(path, name):
    """Copy the current build/mmtt96.bin to .run/mmtt96-health/bins/<name>.bin."""
    d = os.path.join(HEALTH, "bins")
    os.makedirs(d, exist_ok=True)
    out = os.path.join(d, name + ".bin")
    shutil.copyfile(path, out)
    return out


def pair_boundaries(plant):
    """(1) Ghidra listing rows vs Capstone linear sweep over verified code."""
    args = ["--scope", "verified"] + (["--plant", PLANT_ID] if plant else ["--refresh"])
    rc, out = py("boundaries", "scripts/oracle/boundaries.py", *args)
    line = next((l for l in out.splitlines() if l.startswith("boundaries: ")), "")
    counts = line[len("boundaries: "):] if line else "no summary line"
    return rc == 0, "exit %d; %s" % (rc, counts)


def verified_code_ids():
    return [r["id"] for r in read_tsv(REGIONS) if r["kind"] == "code" and r["status"] == "verified"]


def code_ids():
    return [r["id"] for r in read_tsv(REGIONS) if r["kind"] == "code"]


def pair_srcform(plant):
    """(2) instruction-form build (all code rows, verified + inferred, asm/src regenerated by make src) vs all-data SRC= build
    (P1.4-1); a last `make build` leaves the default tree in instruction form."""
    ids = code_ids()
    want = want_sha1()
    try:
        stamp = os.path.join(SRC_DIR, ".stamp")
        if os.path.exists(stamp):  # force the listing to re-run inside make build
            os.remove(stamp)
        rc1, out = run("srcform", [MAKE, "build"])
        rows = [l for l in out.splitlines() if l.startswith("listing ") and not l.endswith("(unrendered)")]
        match = sum(1 for l in rows if l.endswith(", match"))
        mism = len(rows) - match
        lst_ok = rc1 == 0 and match == len(ids) and mism == 0
        with open(SRCLIST, encoding="utf-8") as f:
            used = len(f.read().split()) - 1
        insn = keep(BIN, "srcform_insn") if rc1 == 0 and os.path.exists(BIN) else None
        rc2, _ = run("srcform", [MAKE, "build", "SRC="])
        data = keep(BIN, "srcform_data") if rc2 == 0 and os.path.exists(BIN) else None
    finally:
        run("srcform", [MAKE, "build"])
    if plant and insn:
        insn = flip(insn)
    h1 = sha1(insn) if insn else ""
    h2 = sha1(data) if data else ""
    ok1, ok2 = h1 == want, h2 == want
    same = bool(insn and data) and open(insn, "rb").read() == open(data, "rb").read()
    agree = lst_ok and used == len(ids) and ok1 and ok2 and same
    return agree, "listings %d/%d match, %d mismatch; src used %d/%d; insn hash %s; data hash %s; bins %s" % (
        match, len(ids), mism, used, len(ids), "OK" if ok1 else "BAD", "OK" if ok2 else "BAD",
        "equal" if same else "differ")


def pair_incremental(plant):
    """(3) incremental build vs clean rebuild (G9)."""
    want = want_sha1()
    rc1, _ = run("incremental", [MAKE, "build"])
    inc = keep(BIN, "incremental") if rc1 == 0 and os.path.exists(BIN) else None
    rc2, _ = run("incremental", [MAKE, "clean"])
    rc3, _ = run("incremental", [MAKE, "build"])
    clean = keep(BIN, "clean") if rc2 == 0 and rc3 == 0 and os.path.exists(BIN) else None
    if plant and inc:
        inc = flip(inc)
    h1 = sha1(inc) if inc else ""
    h2 = sha1(clean) if clean else ""
    agree = h1 == want and h2 == want
    return agree, "incremental hash %s; clean hash %s; %s" % (
        "OK" if h1 == want else "BAD", "OK" if h2 == want else "BAD", "equal" if h1 == h2 else "differ")


def manifest_region_records():
    with open(MANIFEST, encoding="utf-8") as f:
        recs = [json.loads(l) for l in f if l.strip()]
    return sum(1 for r in recs if "start" in r and "end" in r and r.get("kind") not in ("decoded", "medium"))


def pair_census(plant):
    """(4) census partition count vs TSV rows, manifest region records and ROM size; progress.py partition."""
    nrows = len(read_tsv(REGIONS))
    mrec = manifest_region_records()
    romsize = os.path.getsize(ROM)
    rc, out = py("census", "scripts/census/census.py")
    line = next((l for l in out.splitlines() if l.startswith("census: regions ")), "")
    try:
        f = line.split()
        n, m = (int(x) for x in f[2].split("/"))
        b, r = (int(x) for x in f[4].split("/"))
    except (IndexError, ValueError):
        n = m = b = r = -1
    tsv = REGIONS
    if plant:
        tsv = os.path.join(scratch("census"), "regions.tsv")
        with open(REGIONS, encoding="utf-8", newline="") as fi:
            lines = fi.read().split("\n")
        c = lines[1].split("\t")
        c[1] = "0x%06X" % (int(c[1], 16) - 2)  # shorten the first row: a 2-byte partition gap
        lines[1] = "\t".join(c)
        with open(tsv, "w", encoding="utf-8", newline="") as fo:
            fo.write("\n".join(lines))
    prc, _ = py("census", "scripts/census/progress.py", "--tsv", tsv)
    agree = rc == 0 and n == m == nrows == mrec and b == r == romsize and prc == 0
    return agree, "census exit %d regions %d/%d (tsv %d, manifest %d) bytes %d/%d (rom %d); progress exit %d" % (
        rc, n, m, nrows, mrec, b, r, romsize, prc)


def pair_mirror(plant):
    """(5) config/regions.retail.tsv vs config/ghidra/regions.tsv row for row."""
    a = read_tsv(REGIONS)
    b = read_tsv(GHIDRA_REGIONS)
    if plant:
        b = [dict(r) for r in b]
        b[0]["note"] = b[0]["note"] + "x"
        path = os.path.join(scratch("mirror"), "regions.tsv")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("start\tend\ttype\tnote\n" + "".join(
                "%s\t%s\t%s\t%s\n" % (r["start"], r["end"], r["type"], r["note"]) for r in b))
        b = read_tsv(path)
    bad = sum(1 for x, y in zip(a, b) if (x["start"], x["end"], x["kind"], "%s; %s; %s" % (
        x["id"], x["status"], x["evidence"])) != (y["start"], y["end"], y["type"], y["note"]))
    bad += abs(len(a) - len(b))
    return bad == 0, "rows %d/%d, %d differ" % (len(a), len(b), bad)


def pair_coverage(plant):
    """(6) executed PCs (coverage.tsv) vs code rows."""
    tsv = COVERAGE_TSV
    if plant:
        with open(COVERAGE_TSV, encoding="utf-8") as f:
            lines = f.read().splitlines()
        cov = [(int(c[0], 16), int(c[1], 16)) for c in (l.split("\t") for l in lines[1:])]
        runs = lines[1].split("\t")[2]
        data = [(int(r["start"], 16), int(r["end"], 16)) for r in read_tsv(REGIONS) if r["kind"] == "data"]
        s = next(ds for ds, de in data if de - ds >= 2 and not any(cs <= ds + 2 and ds <= ce for cs, ce in cov))  # not touching
        rows = sorted(cov + [(s, s + 2)])
        body = []
        for cs, ce in rows:
            orig = next((l for l in lines[1:] if int(l.split("\t")[0], 16) == cs), None)
            body.append(orig if orig and (cs, ce) != (s, s + 2) else "%06X\t%06X\t%s" % (cs, ce, runs))
        tsv = os.path.join(scratch("coverage"), "coverage.tsv")
        with open(tsv, "w", encoding="utf-8", newline="\n") as f:
            f.write(lines[0] + "\n" + "\n".join(body) + "\n")
    rc, out = py("coverage", "scripts/oracle/coverage.py", "--check", "--tsv", tsv)
    faults = sum(1 for l in out.splitlines() if l.startswith("coverage: ") and not l.endswith(" ok"))
    return rc == 0, "exit %d; %d faults" % (rc, faults)


def pair_checkmaps(plant):
    """(7) check_maps.py offline: MAME datapoints and BizHawk second-oracle runs per claim (P1.2-1)."""
    args = []
    if plant:
        path = os.path.join(scratch("checkmaps"), "rom.tsv")
        with open(ROM_MAPS, encoding="utf-8") as f:
            lines = f.read().splitlines()
        hdr = lines[0].split("\t")
        c = lines[1].split("\t")
        i = hdr.index("datapoints")
        c[i] = ";".join(c[i].split(";")[:2])  # a claim with 2 datapoints (< 3)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(lines[0] + "\n" + "\t".join(c) + "\n")
        args = ["--maps", path]
    rc, out = py("checkmaps", "scripts/oracle/check_maps.py", *args)
    fails = sum(1 for l in out.splitlines() if l.startswith("check_maps: FAIL"))
    ok = next((l.split()[2] for l in out.splitlines() if l.startswith("check_maps: OK ")), "0")
    return rc == 0, "exit %d; %s claims ok; %d failures" % (rc, ok, fails)


def pair_signatures(plant):
    """(8) signatures.py check of config/names/routines.tsv vs a scratch control row recomputed from a fresh scan."""
    rc1, out1 = py("signatures", "scripts/census/signatures.py", "check")
    rc0, _ = py("signatures", "scripts/census/signatures.py", "scan")
    fns = [r for r in read_tsv(os.path.join(ROOT, ".run", "signatures", "functions.tsv")) if r["kind"] == "function"]
    b = next((r for r in fns if int(r["nN"]) >= 2), fns[0])
    sig = b["normalised"][:16]
    if plant:
        sig = sig[:-1] + ("0" if sig[-1] != "0" else "1")  # a drifted sighash must make check fire
    path = os.path.join(scratch("signatures"), "routines.tsv")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("addr\tname\tkind\tgroup\tlayer\tsighash\tregion\tevidence\n")
        f.write("%s\tsig_control\tcode\t%s\tnormalised\t%s\t%s\tcontrol\n" % (b["start"], b["gN"], sig, b["region"]))
    rc2, _ = py("signatures", "scripts/census/signatures.py", "check", "--registry", path)
    rows = next((l for l in out1.splitlines() if l.startswith("check: ")), "check: no summary line")
    return rc0 == rc1 == rc2 == 0, "registry check exit %d (%s); scan exit %d; control check exit %d" % (
        rc1, rows[len("check: "):], rc0, rc2)


NAMES_STRIDE = 30  # names pair subset: every 30th verified code id (sorted) -> ~9 regions


def pair_names(plant):
    """(9) db.py listing names-on vs --no-names over a verified code subset: both self-checks match, the on-listing
    uses >= 1 name, each line de-named through config/ghidra/symbols.tsv equals its raw line numerically (code only; the eol comment
    after the first "\t;" and a comment-only plate line are compared raw, not de-named), and every
    config/names ram/code row sits at the same addr in symbols.tsv (the mirror; a wrong equate is self-consistent in
    the listing alone, so this leg is what makes it fire)."""
    import re
    names_dir = os.path.join(ROOT, "config", "names")
    if plant:  # scratch copy of config/names with the first ram.tsv row moved by 2
        names_dir = scratch("names")
        for n in os.listdir(os.path.join(ROOT, "config", "names")):
            shutil.copyfile(os.path.join(ROOT, "config", "names", n), os.path.join(names_dir, n))
        with open(os.path.join(names_dir, "ram.tsv"), encoding="utf-8") as f:
            lines = f.read().split("\n")
        c = lines[1].split("\t")
        c[0] = "0x%06X" % (int(c[0], 16) + 2)
        lines[1] = "\t".join(c)
        with open(os.path.join(names_dir, "ram.tsv"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))
    ids = sorted(verified_code_ids())[::NAMES_STRIDE]
    out = {k: os.path.join(HEALTH, "names", k) for k in ("on", "off")}
    rcs, ok = {}, {}
    for k, extra in (("on", ["--names", names_dir]), ("off", ["--no-names"])):
        shutil.rmtree(out[k], ignore_errors=True)
        rcs[k], o = py("names", "scripts/ghidra/db.py", "listing", *ids, "--out", out[k], *extra)
        ok[k] = sum(1 for l in o.splitlines() if l.startswith("listing ") and l.endswith(", match"))
    syms = {r["name"]: int(r["addr"], 16) for r in read_tsv(os.path.join(ROOT, "config", "ghidra", "symbols.tsv"))}
    at = {int(r["addr"], 16): r["name"] for r in read_tsv(os.path.join(ROOT, "config", "ghidra", "symbols.tsv"))}
    fields = {"%s_%s" % (r["struct"], r["field"]): int(r["offset"], 16)
              for r in read_tsv(os.path.join(names_dir, "structs.tsv"))}
    ident, hexn = re.compile(r"[A-Za-z_][A-Za-z0-9_]*"), re.compile(r"\$([0-9A-Fa-f]+)")
    used, diff = set(), 0

    def norm(line, on):
        if on:
            def sub(m):
                v = syms.get(m.group(0), fields.get(m.group(0)))
                if v is None:
                    return m.group(0)
                used.add(m.group(0))
                return str(v)
            line = ident.sub(sub, line)
        line = hexn.sub(lambda m: str(int(m.group(1), 16) & 0xFFFFFF), line)
        while True:
            s = re.sub(r"\b(\d+)\+(\d+)\b", lambda m: str((int(m.group(1)) + int(m.group(2))) & 0xFFFFFF), line)
            if s == line:
                return line
            line = s

    def same(x, y):  # code de-named, the eol/trailer after the first "\t;" compared raw
        if x.lstrip().startswith(";") or y.lstrip().startswith(";"):  # plate/comment-only line: raw (T33)
            return x == y
        (cx, _, tx), (cy, _, ty) = x.partition("\t;"), y.partition("\t;")
        return norm(cx, True) == norm(cy, False) and tx == ty
    for rid in ids:
        try:
            a, b = (open(os.path.join(out[k], rid + ".asm"), encoding="ascii").read().splitlines() for k in ("on", "off"))
        except OSError:
            diff += 1
            continue
        diff += abs(len(a) - len(b)) + sum(1 for x, y in zip(a, b) if x != y and not same(x, y))
    rows = [r for f in ("ram.tsv", "routines.tsv") for r in read_tsv(os.path.join(names_dir, f))
            if f == "ram.tsv" or r["kind"] == "code"]
    unmirrored = sum(1 for r in rows if at.get(int(r["addr"], 16)) != r["name"])
    agree = rcs["on"] == rcs["off"] == 0 and ok["on"] == ok["off"] == len(ids) and used and not diff and not unmirrored
    return bool(agree), "regions %d; on %d/%d match, off %d/%d match; names used %d; lines differ %d; unmirrored %d/%d" % (
        len(ids), ok["on"], len(ids), ok["off"], len(ids), len(used), diff, unmirrored, len(rows))


PAIRS = {
    "boundaries": pair_boundaries,
    "srcform": pair_srcform,
    "incremental": pair_incremental,
    "census": pair_census,
    "mirror": pair_mirror,
    "coverage": pair_coverage,
    "checkmaps": pair_checkmaps,
    "signatures": pair_signatures,
    "names": pair_names,
}


def summary():
    lines, a = [], 0
    for name in PAIRS:
        path = os.path.join(PAIRS_DIR, name)
        line = open(path, encoding="utf-8").read().strip() if os.path.isfile(path) else ""
        if not line.startswith("pair %s: " % name):
            line = "pair %s: DISAGREE (no result this run)" % name
        a += line.startswith("pair %s: agree" % name)
        lines.append(line)
    lines.append("health: pairs %d/%d agree" % (a, len(PAIRS)))
    os.makedirs(HEALTH, exist_ok=True)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0 if a == len(PAIRS) else 1


def main(argv):
    if argv[:1] == ["summary"] and len(argv) == 1:
        return summary()
    if not argv or argv[0] not in PAIRS or argv[1:] not in ([], ["--plant"]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    name, plant = argv[0], argv[1:] == ["--plant"]
    try:
        agree, counts = PAIRS[name](plant)
    except Exception as e:  # a crashed pair is a disagreement, never a pass
        agree, counts = False, "error %s" % type(e).__name__
    line = "pair %s: %s (%s)" % (name, "agree" if agree else "DISAGREE", counts)
    print(("[plant] " if plant else "") + line)
    if not plant:
        os.makedirs(PAIRS_DIR, exist_ok=True)
        with open(os.path.join(PAIRS_DIR, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(line + "\n")
    return 0 if agree else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
